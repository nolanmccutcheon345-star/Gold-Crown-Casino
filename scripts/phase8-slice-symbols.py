#!/usr/bin/env python3
"""Phase 8 slice 1: slice Nolan's symbol sheets into per-symbol WebP assets.

Grid layouts and reading-order art keys were verified by Maverick against
src/slots/machines.ts (see the Phase 8 build brief). Cells are cropped with a
small inset to dodge printed grid lines, kept square (sheet background and
all, per brief), resized to 288x288 and saved as WebP q85.

Also writes the runtime manifest src/slots/symbol-images.ts and contact
sheets under /tmp/p8-contact/ for visual verification.
"""
from PIL import Image, ImageDraw
import os, sys

REPO = os.path.expanduser('~/workspace/gold-crown-casino-repo')
ART = os.path.expanduser('~/workspace/gold-crown-casino/art/symbols')
OUT = os.path.join(REPO, 'public/casino-art/symbols')
CONTACT = '/tmp/p8-contact'
os.makedirs(CONTACT, exist_ok=True)

# machine -> (cols, rows, [art keys in reading order]); cells beyond the list
# are empty or unmapped extras and are skipped.
SHEETS = {
    'lucky-sevens':     (3, 2, ['seven', 'bar3', 'bar2', 'bar1', 'cherry', 'wheel']),
    'wheel-of-riches':  (4, 2, ['seven', 'bar3', 'bar2', 'bar1', 'cherry', 'wheel']),  # 7th cell: diamond, no such symbol
    'triple-diamond':   (4, 2, ['diamondWild', 'seven', 'bar3', 'bar2', 'bar1', 'cherry', 'wheel']),
    'lucky-lightning':  (3, 3, ['coin', 'bolt', 'seven', 'bell', 'star', 'A', 'K', 'Q', 'J']),
    'gold-rush':        (4, 3, ['goldWild', 'nugget', 'pickaxe', 'lantern', 'cart', 'A', 'K', 'Q', 'J', 'T']),
    'pirates-plunder':  (4, 3, ['helm', 'map', 'chest', 'compass', 'anchor', 'coin', 'A', 'K', 'Q', 'J', 'T']),
    'gem-cascade':      (5, 2, ['ruby', 'emerald', 'sapphire', 'amethyst', 'topaz', 'citrine', 'onyx', 'pearl', 'diamond', 'bomb']),
    'dust-devil':       (4, 3, ['sheriff', 'sunset', 'hat', 'boot', 'horseshoe', 'wagon', 'cactus', 'A', 'K', 'Q', 'J', 'T']),
    'stampede-run':     (4, 3, ['eagle', 'mesa', 'buffalo', 'wolf', 'puma', 'bear', 'A', 'K', 'Q', 'J', 'T']),
    'poseidons-bounty': (4, 3, ['trident', 'seaPearl', 'shell', 'seahorse', 'turtle', 'anchor', 'compass', 'A', 'K', 'Q', 'J']),
    'crown-wheel':      (5, 2, ['crown', 'scepter', 'orb', 'seven', 'bell', 'star', 'A', 'K', 'Q', 'J']),
    'northern-lights':  (3, 3, ['icegem', 'aurora', 'glacier', 'violet', 'amber', 'moonstone', 'rose', 'shadow', 'bomb']),
    'olympus-gold':     (5, 2, ['boltZeus', 'laurel', 'column', 'owl', 'lyre', 'A', 'K', 'Q', 'J', 'T']),
}
INSET = 0.015   # fraction of cell size shaved off each edge (grid-line dodge)
SIZE = 288

manifest = {}
total = 0
for machine, (cols, rows, keys) in SHEETS.items():
    src = Image.open(os.path.join(ART, f'symbols-{machine}.jpg')).convert('RGB')
    W, H = src.size
    cw, ch = W / cols, H / rows
    assert abs(cw - ch) < 2.5, f'{machine}: cells not square ({cw}x{ch})'
    mdir = os.path.join(OUT, machine)
    os.makedirs(mdir, exist_ok=True)
    manifest[machine] = {}
    thumbs = []
    for i, key in enumerate(keys):
        r, c = divmod(i, cols)
        x0, y0 = c * cw, r * ch
        box = (int(x0 + cw * INSET), int(y0 + ch * INSET),
               int(x0 + cw * (1 - INSET)), int(y0 + ch * (1 - INSET)))
        cell = src.crop(box).resize((SIZE, SIZE), Image.LANCZOS)
        path = os.path.join(mdir, f'{key}.webp')
        cell.save(path, 'WEBP', quality=85)
        manifest[machine][key] = f'/casino-art/symbols/{machine}/{key}.webp'
        thumbs.append((key, cell.copy()))
        total += 1
    # contact sheet for this machine
    tw = 220
    sheet = Image.new('RGB', (cols * tw, rows * (tw + 16)), (24, 24, 24))
    d = ImageDraw.Draw(sheet)
    for i, (key, cell) in enumerate(thumbs):
        r, c = divmod(i, cols)
        t = cell.resize((tw, tw), Image.LANCZOS)
        sheet.paste(t, (c * tw, r * (tw + 16)))
        d.text((c * tw + 4, r * (tw + 16) + tw + 3), key, fill=(255, 220, 120))
    sheet.save(os.path.join(CONTACT, f'{machine}.png'))
    print(f'{machine}: {len(keys)} symbols sliced from {W}x{H} ({cols}x{rows})')

# manifest module
lines = ['/** Phase 8: photographic symbol art, sliced from Nolan\'s generated sheets',
         ' * (art/symbols/symbols-<machine>.jpg; reading orders verified against machines.ts).',
         ' * Generated by scripts/phase8-slice-symbols.py — do not hand-edit; re-run the script.',
         ' * A missing entry means the reel renderer falls back to the code-drawn art in art.ts. */',
         'export const SYMBOL_IMAGES: Readonly<Record<string, Readonly<Record<string, string>>>> = Object.freeze({']
for machine in SHEETS:
    entries = ', '.join(f"{k}: '{v}'" for k, v in manifest[machine].items())
    lines.append(f"  '{machine}': Object.freeze({{ {entries} }}),")
lines.append('});')
lines.append('/** The photographic asset for one symbol on one machine, if it has landed. */')
lines.append('export const symbolImage = (machineId: string, artKey: string): string | undefined => SYMBOL_IMAGES[machineId]?.[artKey];')
with open(os.path.join(REPO, 'src/slots/symbol-images.ts'), 'w') as f:
    f.write('\n'.join(lines) + '\n')
print(f'TOTAL {total} symbol assets; manifest written')
